"""Vendored icon subset for B-roll cards: Lucide (lucide-static 1.49.0, ISC; some glyphs from Feather, MIT).

The SVGs live in icons/lucide/<id>.svg with their license header; LICENSE and LICENSES.json carry the
notices and per-file hashes. The page never loads these files: reel.css holds every glyph as a CSS mask
(`.ico[data-icon="<id>"]`, a data: URI), generated from these files by `python -m reel_director.icons`,
so a staged reel needs no extra assets. tests/test_visuals.py checks that the CSS block is in sync.
"""
import re
from functools import lru_cache
from pathlib import Path
from urllib.parse import quote

HERE = Path(__file__).resolve().parent
SET = HERE / "lucide"
CSS = HERE.parent / "web" / "reel.css"
BEGIN, END = "/* icons:begin", "/* icons:end */"


def ids() -> list[str]:
    return sorted(p.stem for p in SET.glob("*.svg"))


def exists(icon: str | None) -> bool:
    return bool(icon) and (SET / f"{icon}.svg").is_file()


@lru_cache(maxsize=None)
def svg(icon: str) -> str:
    """The glyph's markup, minified (license comment and Lucide classes dropped; stroke kept at 2)."""
    raw = (SET / f"{icon}.svg").read_text()
    raw = re.sub(r"<!--.*?-->", "", raw, flags=re.S)
    raw = re.sub(r'\s*class="[^"]*"', "", raw)
    raw = re.sub(r'\s*(width|height)="24"', "", raw)
    raw = re.sub(r"\s+", " ", raw).replace("> <", "><").replace(" />", "/>").strip()
    return raw.replace("currentColor", "#000")


def data_uri(icon: str) -> str:
    return "data:image/svg+xml," + quote(svg(icon).replace('"', "'"), safe=" '=:/;,.-")


def css_block() -> str:
    head = (f"{BEGIN}: Lucide icons (ISC; Feather-derived glyphs MIT), see src/reel_director/icons/LICENSE.\n"
            "   Generated by `python -m reel_director.icons`; do not edit by hand. */\n")
    rules = [f'.ico[data-icon="{i}"] {{ --ico: url("{data_uri(i)}"); }}' for i in ids()]
    return head + "\n".join(rules) + "\n" + END


def sync(path: Path = CSS) -> bool:
    """Rewrite the generated block in reel.css (between the markers). True when the file changed."""
    text = path.read_text()
    a, b = text.find(BEGIN), text.find(END)
    new = text[:a] + css_block() + text[b + len(END):] if a >= 0 and b > a else text.rstrip("\n") + "\n" + css_block() + "\n"
    if new != text:
        path.write_text(new)
    return new != text
