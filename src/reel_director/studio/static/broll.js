/** B-roll panel (v4): every real-media insert of the last plan with its pick, licence and alternates. The creator
 *  swaps a pick for a free alternate, rejects it (the label card shows instead) or restores it, changes the
 *  treatment, and approves ONE paid generation per reel with its cost shown (per-reel and daily caps enforced by
 *  the server). Decisions land in <project>/media.json and show on the next build or preview. Credits list the
 *  licences the reel must carry. Built only with h() (text, never innerHTML). */
import { brollAction, getBroll } from './api.js';
import { $, h, num } from './dom.js';
import { S } from './state.js';
import { banner, toast } from './ui.js';

const POLL_MS = 5000;
const STATUS = {
  picked: ['picked', 'ok'], swapped: ['your pick', 'ok'], approved: ['approved (paid)', 'ok'],
  rejected: ['label card instead', 'warn'], unresolved: ['no media found: label card', 'warn'],
  awaiting_approval: ['paid option waiting for approval', 'warn'],
};
const TREAT = {
  fullbleed: 'Full-bleed', kenburns: 'Ken Burns', parallax: '2.5D parallax', sticker: 'Sticker pop',
  device: 'Device mockup', polaroid: 'Polaroid stack', reveal: 'Masked reveal', inset: 'Picture-in-picture',
};
let stamp = -1, open = new Set(), busy = false;

const LIC_BAD = /(^|[-\s])(nc|nd)([-\s]|$)|unknown/i, LIC_SA = /(^|[-\s])sa([-\s]|$)/i;   // "cc-by-sa-4.0" -> share-alike
const GEN = new Set(['veo', 'higgsfield', 'claude_clip']);          // made for this reel: label it as AI-generated
/** "cc-by-sa-4.0" -> "CC BY-SA 4.0", "cc0-1.0" -> "CC0 1.0", "pdm" -> "Public domain", "original" -> "Made for this reel". */
const licName = s => !s ? 'licence unknown' : /^cc/i.test(s) ? s.toUpperCase().replace(/^CC-/, 'CC ').replace(/-(\d)/, ' $1')
  : /^(pd|pdm)$/i.test(s) ? 'Public domain' : /^(own|original|user-capture)$/i.test(s) ? 'Made for this reel' : s;
const licence = c => h('span', { class: `badge ${LIC_BAD.test(c?.license || 'unknown') ? 'fail' : LIC_SA.test(c?.license || '') ? 'warn' : 'ok'}`,
  title: c?.attribution || c?.license || '' }, licName(c?.license));
const aiBadge = c => (GEN.has(c?.provider) ? h('span', { class: 'badge warn', title: 'Generated by AI: label it when you post' }, 'AI-generated') : null);
const money = v => `$${num(v, 2)}`;

function thumb(c, cls = 'br-thumb') {
  if (!c?.thumb) return h('div', { class: `${cls} empty` }, c?.kind === 'video' ? '▶' : '—');
  return h('img', { class: cls, src: c.thumb, alt: c.title || c.id || 'B-roll pick', loading: 'lazy', referrerpolicy: 'no-referrer' });
}

async function act(slot, action, q = {}) {
  if (busy) return;
  busy = true;
  try {
    const r = await brollAction(slot, action, q);
    toast(`${slot}: ${STATUS[r.status]?.[0] || r.status}. ${r.next || ''}`, 'ok');
    stamp = -1;
    await refreshBroll();
  } catch (e) {
    banner(`B-roll: ${e.message}`, `broll-${slot}`);
  } finally {
    busy = false;
  }
}

function altRow(it, spend) {
  return h('div', { class: 'br-alts' }, it.alternates.map(a => {
    const paid = a.cost_usd > 0;
    const over = paid && (spend.reel_usd + a.cost_usd > spend.reel_cap_usd || spend.day_usd + a.cost_usd > spend.day_cap_usd);
    const label = paid ? `Approve ${money(a.cost_usd)}` : 'Use this';
    const why = !paid ? '' : !it.paid_ok ? 'Only the reel\'s one paid insert can be generated' : over ? 'Over the per-reel or daily cap' : '';
    const ask = `Approve one ${a.provider} generation for about ${money(a.cost_usd)}?\nIt is generated on the next build or `
      + `preview and counts toward this reel's ${money(spend.reel_cap_usd)} cap and today's ${money(spend.day_cap_usd)} cap.`;
    return h('figure', { class: `br-alt${paid ? ' paid' : ''}` }, thumb(a, 'br-alt-thumb'),
      h('figcaption', {}, h('span', { class: 'small' }, a.title || a.id), h('span', { class: 'small muted' }, a.provider || '?'),
        licence(a), aiBadge(a),
        h('button', { type: 'button', disabled: !!why, title: why || null,
          onclick: () => (!paid || confirm(ask)) && act(it.slot, paid ? 'approve' : 'swap', { alt: a.id }) }, label)));
  }));
}

function item(it, spend, treatments) {
  const [stText, stLevel] = STATUS[it.status] || [it.status || '?', ''];
  const c = it.chosen;
  const pick = h('select', { 'aria-label': `Treatment for ${it.at}`, onchange: e => act(it.slot, 'treatment', { name: e.target.value }) },
    treatments.map(t => h('option', { value: t, selected: t === it.treatment }, TREAT[t] || t)));
  const shown = it.status === 'rejected'
    ? h('button', { type: 'button', onclick: () => act(it.slot, 'restore') }, 'Use the picture again')
    : h('button', { type: 'button', disabled: !c, onclick: () => act(it.slot, 'reject') }, 'Show the label card');
  const more = open.has(it.slot);
  return h('li', { class: `br-item ${it.status}` },
    h('div', { class: 'br-main' }, thumb(c),
      h('div', { class: 'br-meta' },
        h('div', { class: 'br-at' }, h('b', {}, it.shot), ` · “${it.at}”`),
        h('div', { class: 'small muted' }, `${it.media} · ${it.query}`),
        h('div', { class: 'br-badges' }, h('span', { class: `badge ${stLevel}` }, stText),
          c ? licence(c) : null, c ? h('span', { class: 'badge' }, c.provider || '?') : null, aiBadge(c),
          it.paid_ok ? h('span', { class: 'badge warn', title: 'The one insert per reel that may use a paid generator' }, 'paid-eligible') : null),
        c?.attribution ? h('div', { class: 'small muted br-attr' }, c.attribution) : null)),
    h('div', { class: 'br-actions' }, pick, shown,
      h('button', { type: 'button', disabled: !it.alternates.length, 'aria-expanded': String(more),
        onclick: () => { more ? open.delete(it.slot) : open.add(it.slot); stamp = -1; refreshBroll(); } },
        more ? 'Hide alternates' : `Alternates (${it.alternates.length})`)),
    more ? altRow(it, spend) : null,
    it.notes?.length ? h('div', { class: 'small muted' }, it.notes.join(' · ')) : null);
}

export async function refreshBroll() {
  let v;
  try {
    v = await getBroll();
  } catch (e) {
    $('broll-note').textContent = `B-roll panel unavailable: ${e.message}`;
    return;
  }
  if (v.stamp === stamp) return;
  stamp = v.stamp;
  const s = v.spend;
  $('broll-note').textContent = v.note || `${v.items.length} insert(s). Changes show on the next build or preview.`;
  $('broll-spend').textContent = `Paid generations: ${money(s.reel_usd)} of ${money(s.reel_cap_usd)} this reel · `
    + `${money(s.day_usd)} of ${money(s.day_cap_usd)} today. Nothing is generated without your approval.`;
  const yt = $('broll-yt');
  yt.hidden = !v.youtube_warning;
  yt.textContent = v.youtube_warning || '';
  $('broll-list').replaceChildren(...v.items.map(it => item(it, s, v.treatments)));
  $('broll-credits').replaceChildren(...(v.credits || []).map(c => h('li', {}, c)));
  $('broll-credits-box').hidden = !(v.credits || []).length;
}

export function initBroll() {
  refreshBroll();
  setInterval(() => {
    if (!document.hidden && S.rec === 'idle') refreshBroll();   // never compete with a recording
  }, POLL_MS);
}
